import type { Food, Nutrition, Portion, PortionUnit } from '../types';

const p = (unit: PortionUnit, grams: number, quantity = 1): Portion => ({
  unit,
  grams,
  quantity,
});

const n = (
  kcal: number,
  proteinG: number,
  carbsG: number,
  fatG: number,
  fiberG?: number,
  sodiumMg?: number,
): Nutrition => ({ kcal, proteinG, carbsG, fatG, fiberG, sodiumMg });

